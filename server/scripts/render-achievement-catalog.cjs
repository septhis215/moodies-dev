// Produces reviewable SQL only. Never connects to a database.
const fs = require('node:fs');
const path = require('node:path');
require('ts-node').register({
  skipProject: true,
  transpileOnly: true,
  compilerOptions: { module: 'CommonJS', moduleResolution: 'node' },
});
const {
  achievementSeeds,
  rarityTheme,
} = require('../src/achievements/achievement-catalog');
const {
  RULE_TARGETS,
  ACHIEVEMENT_RULE_VERSION,
  DISCOVERY_POLICY,
  QUIZ_TYPES,
} = require('../src/achievements/achievement-rules');
const quote = (value) =>
  value === null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
let sql =
  '-- Generated by node server/scripts/render-achievement-catalog.cjs --write.\n-- Existing user awards are preserved. Run after the engine schema migration.\nBEGIN;\n';
for (const [index, seed] of achievementSeeds.entries()) {
  if (
    !RULE_TARGETS.includes(seed.requirementTarget) ||
    (seed.requiredCount !== null &&
      (!Number.isSafeInteger(seed.requiredCount) || seed.requiredCount < 1))
  )
    throw new Error(`Invalid rule: ${seed.key}`);
  const columns = [
    'key',
    'title',
    'description',
    'category',
    'requirementType',
    'requirementTarget',
    'requiredCount',
    'progressLogic',
    'reasoningTemplate',
    'lockedHint',
  ];
  sql += `INSERT INTO achievements (id,${columns.map((c) => `"${c}"`).join(',')},"ruleVersion",active,"updatedAt") VALUES(gen_random_uuid()::text,${columns.map((c) => quote(seed[c])).join(',')},${ACHIEVEMENT_RULE_VERSION},true,now()) ON CONFLICT(key) DO UPDATE SET ${columns
    .slice(1)
    .map((c) => `"${c}"=EXCLUDED."${c}"`)
    .join(
      ',',
    )},"ruleVersion"=${ACHIEVEMENT_RULE_VERSION},active=true,"updatedAt"=now();\n`;
  const theme = rarityTheme[seed.rarity] || rarityTheme.Common;
  const badge = {
    key: seed.badgeKey,
    badgeName: seed.badgeName,
    icon: seed.icon,
    rarity: seed.rarity,
    mascotMood: seed.mascotMood,
    mascotMotion: seed.mascotMotion,
  };
  const visual = {
    colorTheme: theme,
    lockedVisualState: { opacity: 0.45, treatment: 'muted' },
    unlockedVisualState: {
      glow: theme.glow,
      accent: theme.accent,
      treatment: 'reward',
    },
  };
  sql += `INSERT INTO badge_definitions(id,"achievementId",${Object.keys(badge)
    .map((c) => `"${c}"`)
    .join(',')},${Object.keys(visual)
    .map((c) => `"${c}"`)
    .join(
      ',',
    )},"displayOrder",active,"updatedAt") SELECT gen_random_uuid()::text,id,${Object.values(badge).map(quote).join(',')},${Object.values(visual).map(json).join(',')},${index + 1},true,now() FROM achievements WHERE key=${quote(seed.key)} ON CONFLICT(key) DO UPDATE SET "badgeName"=EXCLUDED."badgeName",icon=EXCLUDED.icon,rarity=EXCLUDED.rarity,"mascotMood"=EXCLUDED."mascotMood","mascotMotion"=EXCLUDED."mascotMotion","colorTheme"=EXCLUDED."colorTheme","displayOrder"=EXCLUDED."displayOrder",active=true,"updatedAt"=now();\n`;
  const definition = {
    ...seed,
    version: ACHIEVEMENT_RULE_VERSION,
    discoveryPolicy: DISCOVERY_POLICY,
    quizTypes: QUIZ_TYPES,
  };
  sql += `INSERT INTO achievement_rule_versions(id,"achievementId",version,target,"requiredCount",definition) SELECT gen_random_uuid()::text,id,${ACHIEVEMENT_RULE_VERSION},${quote(seed.requirementTarget)},${quote(seed.requiredCount)},${json(definition)} FROM achievements WHERE key=${quote(seed.key)} ON CONFLICT("achievementId",version) DO NOTHING;\n`;
  sql += `DO $$ BEGIN IF EXISTS(SELECT 1 FROM public.achievement_rule_versions WHERE "achievementId"=(SELECT id FROM public.achievements WHERE key=${quote(seed.key)}) AND version=${ACHIEVEMENT_RULE_VERSION} AND definition<>${json(definition)}) THEN RAISE EXCEPTION 'Published rule changed without a new version: ${seed.key}'; END IF; END $$;\n`;
}
sql += `INSERT INTO achievement_award_log(id,"userId","achievementId","ruleVersion",action,actor,reason,evidence,"idempotencyKey","createdAt") SELECT gen_random_uuid()::text,"userId","achievementId","ruleVersion",'legacy','migration','Existing unlocked award preserved without inferring historical activity','{"basis":"legacy"}'::jsonb,'legacy:'||id,coalesce("unlockedAt","createdAt") FROM public.user_achievements WHERE unlocked ON CONFLICT("idempotencyKey") DO NOTHING;\nCOMMIT;\n`;
const destination = path.resolve(
  __dirname,
  '../prisma/migrations/20261101090100_achievement_catalog/migration.sql',
);
const security = fs
  .readFileSync(
    path.resolve(
      __dirname,
      '../prisma/migrations/20261101090200_achievement_data_api_security/migration.sql',
    ),
    'utf8',
  )
  .replaceAll('\r\n', '\n');
const body = (script) =>
  script
    .replace(/^BEGIN;\s*$/m, '')
    .replace(/^COMMIT;\s*$/m, '')
    .trim();
const recovery =
  '-- Generated by render-achievement-catalog.cjs --write.\n-- Requires the engine schema migration to be applied already. No table removal.\n-- Supabase SQL Editor: execute the complete file as written; do not auto-append RLS.\n-- Includes catalogue and Data API security migrations in one atomic transaction.\nBEGIN;\n' +
  body(security) +
  '\n' +
  body(sql) +
  '\nCOMMIT;\n';
const recoveryDestination = path.resolve(
  __dirname,
  '../prisma/manual/achievement_catalog_recovery.sql',
);
if (process.argv.includes('--write')) {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, sql);
  fs.mkdirSync(path.dirname(recoveryDestination), { recursive: true });
  fs.writeFileSync(recoveryDestination, recovery);
  console.log(
    'Prepared versioned achievement catalogue and secured recovery SQL.',
  );
} else {
  if (fs.readFileSync(destination, 'utf8').replaceAll('\r\n', '\n') !== sql)
    throw new Error('Catalogue SQL is stale; review and regenerate it.');
  if (
    fs.readFileSync(recoveryDestination, 'utf8').replaceAll('\r\n', '\n') !==
    recovery
  )
    throw new Error('Recovery SQL is stale; review and regenerate it.');
  console.log('Catalogue and secured recovery SQL match their sources.');
}
